#!/usr/bin/env node
// Generates data/dataset-manifest.js: the dataset registration manifest the
// viewer boots from. Each registered adapter contributes one lightweight
// navigation entry (key, script src, display name, canonical company, period
// fields, and display-only i18n) so the catalog/sidebar/search/routing work
// before any adapter file has loaded; src/dataset-registry.js turns entries
// into stub datasets and upgrades them in place as adapters arrive.
//
// Registration order is preserved from the existing manifest (falling back
// to index.html dataset tags, then alphabetical) because adapters may rely
// on loading after a dataset they reuse. New dataset files on disk are
// appended; deleted files are dropped. `--check` fails when the committed
// manifest drifts from disk.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import {
  DATASET_SCRIPT_DIR,
  UNREGISTERED_DATASET_SCRIPTS,
  dataScriptsFromIndex,
} from './script-sources.mjs';
import { listScripts, projectPath, readProjectFile } from './lib/project.mjs';
import { loadClassicScripts } from './lib/vm-browser.mjs';

const OUTPUT_PATH = 'data/dataset-manifest.js';

function parseArgs(argv) {
  const allowed = new Set(['--check']);
  const unknown = argv.slice(2).filter((arg) => !allowed.has(arg));
  if (unknown.length) throw new Error(`Unknown argument(s): ${unknown.join(' ')}`);
  return { check: argv.includes('--check') };
}

function datasetKeyForScript(script) {
  return path.basename(script, '.js');
}

function existingManifestOrder() {
  try {
    const context = loadClassicScripts([OUTPUT_PATH]);
    const entries = context.__DATASET_MANIFEST__?.datasets || [];
    return entries.map((entry) => entry.src).filter(Boolean);
  } catch {
    return [];
  }
}

function orderedDatasetScripts() {
  const onDisk = listScripts(DATASET_SCRIPT_DIR).filter(
    (script) => !UNREGISTERED_DATASET_SCRIPTS.has(script)
  );
  const onDiskSet = new Set(onDisk);
  const seen = new Set();
  const ordered = [];
  const candidates = [
    ...existingManifestOrder(),
    ...dataScriptsFromIndex(readProjectFile('index.html')),
    ...onDisk,
  ];
  for (const script of candidates) {
    if (!onDiskSet.has(script) || seen.has(script)) continue;
    seen.add(script);
    ordered.push(script);
  }
  return ordered;
}

function pickDisplayMeta(meta) {
  const out = {};
  if (meta?.title) out.title = meta.title;
  if (meta?.period) out.period = meta.period;
  if (meta?.periodNote) out.periodNote = meta.periodNote;
  if (meta?.variant) out.variant = meta.variant;
  if (meta?.variantName) out.variantName = meta.variantName;
  if (meta?.viewVariant) out.viewVariant = meta.viewVariant;
  if (meta?.viewVariantName) out.viewVariantName = meta.viewVariantName;
  return out;
}

function displayI18n(datasetI18n, languageCodes) {
  const out = {};
  for (const language of languageCodes) {
    const overlay = datasetI18n?.[language];
    if (!overlay) continue;
    const entry = {};
    if (overlay.name) entry.name = overlay.name;
    const meta = pickDisplayMeta(overlay.meta);
    if (Object.keys(meta).length) entry.meta = meta;
    if (Object.keys(entry).length) out[language] = entry;
  }
  return out;
}

function buildManifest(scripts) {
  const context = loadClassicScripts([
    'src/icons.js',
    'src/sankey-engine.js',
    'src/i18n-dictionaries.js',
    'src/i18n.js',
    'src/trace-domain.js',
    ...listScripts('data/income-statements'),
    'data/revenue-metrics.js',
    ...listScripts('data/company-metadata'),
    ...scripts,
  ]);
  const datasets = context.DATASETS || [];
  const domain = context.TraceDomain;
  const i18n = context.SANKEY_I18N;
  if (!domain) throw new Error('TraceDomain did not load');
  const catalog = domain.createCatalog(context);
  const recordByKey = new Map(catalog.records.map((record) => [record.dataset.key, record]));
  const overlayLanguages = (i18n?.languageCodes || []).filter(
    (code) => code !== (i18n?.defaultLanguage || 'en')
  );

  const entries = scripts.map((src) => {
    const key = datasetKeyForScript(src);
    const dataset = datasets.find((item) => item.key === key);
    if (!dataset) throw new Error(`Dataset script did not register key "${key}": ${src}`);
    const record = recordByKey.get(key);
    const data = {
      name: dataset.name || '',
      company: record?.company || '',
      meta: pickDisplayMeta(dataset.meta),
    };
    const i18nOverlay = displayI18n(dataset.i18n, overlayLanguages);
    if (Object.keys(i18nOverlay).length) data.i18n = i18nOverlay;
    return { key, src, data };
  });

  return { datasets: entries };
}

function renderSource(manifest) {
  const body = JSON.stringify(manifest, null, 2);
  return `/*\n * Generated by scripts/update-dataset-manifest.mjs.\n * Do not edit by hand. Registration lives here (not index.html); run\n * pnpm sync:index-datasets after adding or removing dataset files.\n */\n(function () {\n  var manifest = ${body.replace(/\n/g, '\n  ')};\n  // VM verifiers read the plain object; the browser installs stubs.\n  window.__DATASET_MANIFEST__ = manifest;\n  if (window.TraceDatasetRegistry) window.TraceDatasetRegistry.installManifest(manifest);\n})();\n`;
}

async function main() {
  const { check } = parseArgs(process.argv);
  const scripts = orderedDatasetScripts();
  const source = renderSource(buildManifest(scripts));
  const target = projectPath(OUTPUT_PATH);
  if (check) {
    let existing = '';
    try {
      existing = await readFile(target, 'utf8');
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (existing !== source) {
      throw new Error('Dataset manifest is stale. Run pnpm sync:index-datasets (or node scripts/update-dataset-manifest.mjs).');
    }
    console.log(`${OUTPUT_PATH} is current (${scripts.length} dataset(s))`);
    return;
  }
  await writeFile(target, source);
  console.log(`wrote ${OUTPUT_PATH}: ${scripts.length} dataset(s)`);
}

main().catch((err) => {
  console.error(err.stack || err.message);
  process.exit(1);
});
